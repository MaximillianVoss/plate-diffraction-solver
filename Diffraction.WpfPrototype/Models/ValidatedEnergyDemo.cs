public sealed class EnergyDemoSnapshot
{
    public EnergyDemoSnapshot(
        double skinDepth,
        double reflectedScattered,
        double forwardScattered,
        double absorbed,
        double sheetAbove,
        double sheetBelow,
        double fluxAbsorbed,
        double localBalanceErrorPercent)
    {
        SkinDepth = skinDepth;
        ReflectedScattered = reflectedScattered;
        ForwardScattered = forwardScattered;
        Absorbed = absorbed;
        SheetAbove = sheetAbove;
        SheetBelow = sheetBelow;
        FluxAbsorbed = fluxAbsorbed;
        LocalBalanceErrorPercent = localBalanceErrorPercent;
    }

    public double SkinDepth { get; }
    public double ReflectedScattered { get; }
    public double ForwardScattered { get; }
    public double Absorbed { get; }
    public double SheetAbove { get; }
    public double SheetBelow { get; }
    public double FluxAbsorbed { get; }
    public double LocalBalanceErrorPercent { get; }

    public double FarFieldMismatchPercent =>
        Math.Abs(ReflectedScattered - ForwardScattered) * 100.0;

    public double SheetMismatchPercent =>
        Math.Abs(SheetAbove - SheetBelow) * 100.0;

    public double LocalBalanceTotal =>
        1.0 - LocalBalanceErrorPercent / 100.0;

    public string ReflectedDisplay => $"{ReflectedScattered:0.000}";
    public string ForwardDisplay => $"{ForwardScattered:0.000}";
    public string AbsorbedDisplay => $"{Absorbed:0.000}";
    public string SkinDepthDisplay => $"{SkinDepth:0.000000}";
    public string ReflectedPercentDisplay => $"{ReflectedScattered:P1} от I_plate";
    public string ForwardPercentDisplay => $"{ForwardScattered:P1} от I_plate";
    public string AbsorbedPercentDisplay => $"{Absorbed:P1} от I_plate";
    public string LocalBalanceErrorDisplay => $"{LocalBalanceErrorPercent:0.000}%";
    public string LocalBalanceResidualDisplay =>
        $"|ΔЗСЭ| / I_plate = {LocalBalanceErrorPercent:0.000}%";
    public string CompactBalanceDisplay =>
        $"ЗСЭ в допуске  •  |Δ| / I_plate = {LocalBalanceErrorPercent:0.000}%";
    public string SheetPairDisplay => $"{SheetAbove:0.000} / {SheetBelow:0.000}";
    public string DiagnosticsSummary =>
        $"Локальный ЗСЭ: невязка {LocalBalanceErrorPercent:0.000}% (допуск 2,00%).\n" +
        $"R_scat / T_scat: {ReflectedScattered:0.000000} / {ForwardScattered:0.000000}; совпадают в пределах машинной точности.\n" +
        $"Потоки рассеяния сверху / снизу у листа: {SheetAbove:0.000000} / {SheetBelow:0.000000}.\n" +
        "T_scat — рассеянное поле вперёд; полное прохождение дополнительно учитывает падающее поле и интерференцию.";
}

