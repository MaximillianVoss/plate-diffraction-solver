    private static double Interpolate(double argument, double[] arguments, double[] values)
    {
        if (argument <= arguments[0])
            return values[0];
        if (argument >= arguments[arguments.Length - 1])
            return values[values.Length - 1];

        int upper = Array.BinarySearch(arguments, argument);
        if (upper >= 0)
            return values[upper];

        upper = ~upper;
        int lower = upper - 1;
        double fraction = (argument - arguments[lower]) / (arguments[upper] - arguments[lower]);
        return values[lower] + fraction * (values[upper] - values[lower]);
    }
